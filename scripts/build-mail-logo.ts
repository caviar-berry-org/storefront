/**
 * Rasterises the brand emblem for transactional email.
 *
 *   node scripts/build-mail-logo.ts [--dry-run]
 *
 * Mail clients do not render SVG (Gmail and Outlook strip it outright), so the
 * emblem ships as a PNG. Like the banner it travels as a CID attachment rather
 * than a hosted file: remote images are blocked by default in most clients and
 * leak a read signal back to the sender.
 *
 * Encoded at 2x the display width so it stays sharp on retina screens. The
 * emblem is a single mid-gold (#8f7c33) on transparency, which keeps it legible
 * on both the light card and the dark-mode palette.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import sharp from "sharp";

const root = process.cwd();
const source = path.join(root, "public/assets/img/logo-emblem.svg");
const output = path.join(root, "src/content/mail/logo.ts");
const dryRun = process.argv.includes("--dry-run");

/** Display width in the mail header; the raster is encoded at twice this. */
const displayWidth = 104;
const aspect = 87 / 114;

const png = await sharp(await readFile(source), { density: 288 })
  .resize({ width: displayWidth * 2 })
  .png({ compressionLevel: 9, palette: true })
  .toBuffer();

const base64 = png.toString("base64");
const file = `// Generated by scripts/build-mail-logo.ts — do not edit by hand.
// Brand emblem for the mail header, embedded as a CID attachment (see the script
// for why it is neither SVG nor a hosted image).

export const mailLogo =
  "${base64}";

export const mailLogoCid = "caviar-berry-logo";

/** Rendered width in the mail header; the raster is twice this for retina. */
export const mailLogoWidth = ${displayWidth};
export const mailLogoHeight = ${Math.round(displayWidth * aspect)};
`;

console.log(
  `Emblem → PNG ${displayWidth * 2}px wide, ${(png.length / 1024).toFixed(1)} KB (${(base64.length / 1024).toFixed(1)} KB base64).`,
);
if (dryRun) console.log("Dry run: src/content/mail/logo.ts not written.");
else {
  await writeFile(output, file, "utf8");
  console.log(`Wrote ${path.relative(root, output)}.`);
}
